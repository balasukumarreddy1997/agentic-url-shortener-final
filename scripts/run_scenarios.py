"""Run the three assignment scenarios end to end and write their real audit trails.

    py scripts/run_scenarios.py                 # writes docs/scenario-runs/*.md
    py scripts/run_scenarios.py --out somewhere

Every workflow uses the real agents, including the pytest subprocess. Human actions
(clarification, approvals, a requirement change) are performed by distinct named actors
through the same engine methods the HTTP API calls, so the output is exactly what an
operator would see. A fourth run injects a failing security check to show the release
gate failing closed. Workflow state and artifacts go to a temporary directory; only the
Markdown reports are written to --out.
"""

from __future__ import annotations

import argparse
import asyncio
import os
import sys
import tempfile
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

_TMP = Path(tempfile.mkdtemp(prefix="scenario-runs-"))
os.environ.setdefault("AGENTIC_ARTIFACTS_DIR", str(_TMP / "artifacts"))

from orchestrator.agents import AgentRegistry
from orchestrator.engine import WorkflowEngine
from orchestrator.models import WorkflowRun
from orchestrator.persistence import WorkflowRepository

SKIP_DETAIL_KEYS = {"description"}


def new_engine(name: str, agents: AgentRegistry | None = None) -> WorkflowEngine:
    return WorkflowEngine(
        agents=agents or AgentRegistry(project_root=ROOT),
        repository=WorkflowRepository(str(_TMP / f"{name}.db")),
    )


def fmt_details(details: dict) -> str:
    parts = []
    for key, value in details.items():
        if key in SKIP_DETAIL_KEYS or value in (None, "", [], {}):
            continue
        text = str(value).replace(str(_TMP / "artifacts") + os.sep, "<artifacts>/")
        if len(text) > 90:
            text = text[:87] + "..."
        parts.append(f"{key}={text}")
    joined = ", ".join(parts).replace(str(_TMP / "artifacts") + os.sep, "<artifacts>/")
    return joined.replace("|", "\\|")


def report(title: str, narrative: list[str], run: WorkflowRun, engine: WorkflowEngine) -> str:
    start = run.audit[0].timestamp if run.audit else run.created_at
    lines = [
        f"# {title}",
        "",
        "Generated by `scripts/run_scenarios.py` from a real run; not hand-written.",
        "",
        f"- **Scenario:** `{run.scenario}`",
        f"- **Final requirement:** {run.requirement}",
        f"- **Requested by:** `{run.context.get('requested_by')}`",
        f"- **Final status:** `{run.status}` (plan generation {run.replan_count})",
        "",
        "## What happened",
        "",
        *[f"{i}. {step}" for i, step in enumerate(narrative, 1)],
        "",
        "## Final task states",
        "",
        "| Task | Stage | Status | Attempts | Gate |",
        "|---|---|---|---|---|",
    ]
    for task in run.tasks.values():
        gate = "input" if task.requires_input else ("approval" if task.requires_approval else "")
        lines.append(
            f"| `{task.id}` | {task.stage} | {task.status.value} | {task.attempts} | {gate} |"
        )
    lines += [
        "",
        "## Human decisions (lineage)",
        "",
        "| Gen | Type | Who | Detail |",
        "|---|---|---|---|",
    ]
    for d in run.decisions:
        if d.get("type") == "clarification":
            who, detail = d["answered_by"], f"{d['question']} → {d['answer']}"
        else:
            who = d["approver"]
            verdict = "approved" if d["approved"] else "denied"
            detail = f"{verdict} `{d['task_id']}`: {d.get('reason', '')}"
        lines.append(
            f"| {d.get('generation', 0)} | {d.get('type', 'approval')} | `{who}` | {detail} |"
        )
    lines += ["", "## Audit trail", "", "| +ms | Event | Task | Details |", "|---|---|---|---|"]
    t0 = datetime.fromisoformat(start)
    for e in run.audit:
        offset = int((datetime.fromisoformat(e.timestamp) - t0).total_seconds() * 1000)
        lines.append(f"| {offset} | `{e.event}` | {e.task_id or ''} | {fmt_details(e.details)} |")
    m = engine.metrics_snapshot()
    lines += [
        "",
        "## Metrics for this engine",
        "",
        (
            f"success_rate={m['success_rate']}, retries={m['retries']}, "
            f"rollbacks={m['rollbacks']}, mttr_ms={m['mttr_ms']}, "
            f"average_execution_ms={m['average_execution_ms']}, "
            f"average_lead_time_ms={m['average_lead_time_ms']}"
        ),
        "",
    ]
    return "\n".join(lines)


async def greenfield():
    engine = new_engine("greenfield")
    run = engine.create_run(
        "greenfield", "Build a URL shortener with click analytics", requested_by="priya"
    )
    narrative = ["`priya` requests a new URL shortener with analytics."]
    run = await engine.execute(run.id)
    narrative.append(
        f"Requirements and design run; three branches start in parallel. Run pauses at "
        f"`{run.status}` on `implement_orchestrator` (high risk)."
    )
    engine.approve(run.id, "implement_orchestrator", True, "marcus", "Scope and design reviewed")
    run = await engine.execute(run.id)
    narrative.append(
        "`marcus` approves. Tests (real pytest subprocess), security review and docs run. "
        "Run pauses at the release gate with upstream evidence attached to the request."
    )
    engine.approve(run.id, "release_gate", True, "lena", "Tests green, no security findings")
    run = await engine.execute(run.id)
    narrative.append(f"`lena` approves the release. Evidence gate passes; run `{run.status}`.")
    return "01-greenfield.md", report("Greenfield: new URL shortener", narrative, run, engine)


async def brownfield():
    engine = new_engine("brownfield")
    run = engine.create_run(
        "brownfield",
        "Add per-link expiration without breaking existing short links",
        requested_by="priya",
    )
    narrative = ["`priya` requests a backward-compatible enhancement to the existing service."]
    run = await engine.execute(run.id)
    engine.approve(run.id, "implement_orchestrator", True, "marcus", "Expiry design approved")
    run = await engine.execute(run.id)
    narrative.append(
        f"`marcus` approves implementation; validation runs and the run reaches `{run.status}` "
        "at the release gate."
    )
    run = engine.replan(
        run.id,
        "Add per-link expiration, plus an admin endpoint to extend expiry, without breaking "
        "existing short links",
    )
    narrative.append(
        "Before release, the requirement changes (an admin extension endpoint is added). "
        "`replan` rebuilds the plan as generation 1; all completed work and the earlier approval are "
        "invalidated, but kept in the lineage."
    )
    run = await engine.execute(run.id)
    narrative.append(
        f"Re-execution pauses again at `implement_orchestrator`: `marcus`'s generation-0 "
        f"approval cannot authorize the changed plan (status `{run.status}`)."
    )
    engine.approve(
        run.id, "implement_orchestrator", True, "marcus", "Re-reviewed with admin endpoint"
    )
    run = await engine.execute(run.id)
    engine.approve(run.id, "release_gate", True, "lena", "Regression suite green")
    run = await engine.execute(run.id)
    narrative.append(
        f"Fresh approvals for generation 1; regression tests pass; run `{run.status}`."
    )
    return "02-brownfield.md", report(
        "Brownfield: backward-compatible enhancement with a mid-flight requirement change",
        narrative,
        run,
        engine,
    )


async def ambiguous():
    engine = new_engine("ambiguous")
    run = engine.create_run("ambiguous", "make links short", requested_by="priya")
    narrative = ["`priya` submits a one-line, underspecified request."]
    run = await engine.execute(run.id)
    questions = run.context["human_questions"]
    narrative.append(
        f"`understand` raises {len(questions)} open questions. Run pauses at `{run.status}`; "
        "design has not started."
    )
    try:
        engine.clarify(run.id, {questions[0]: "30 days"}, "priya")
    except ValueError as exc:
        narrative.append(f"A partial answer is refused: _{exc}_.")
    answers = dict(
        zip(
            questions,
            [
                "Links expire after 30 days by default; configurable per link",
                "Anonymous creation for the prototype; ownership deferred",
                "60 creates per minute per client IP",
            ],
            strict=False,
        )
    )
    for q in questions:
        answers.setdefault(q, "Accept the documented default")
    engine.clarify(run.id, answers, "priya")
    run = await engine.execute(run.id)
    narrative.append(
        "`priya` answers every question. Answers are recorded as decisions and flow into the "
        f"design output. Run pauses at `{run.status}`."
    )
    try:
        engine.approve(run.id, "implement_orchestrator", True, "priya", "Looks fine to me")
    except ValueError as exc:
        narrative.append(f"`priya` tries to approve her own run and is refused: _{exc}_.")
    engine.approve(run.id, "implement_orchestrator", True, "marcus", "Assumptions acceptable")
    run = await engine.execute(run.id)
    engine.approve(run.id, "release_gate", True, "lena", "Evidence reviewed")
    run = await engine.execute(run.id)
    narrative.append(f"Independent approvals by `marcus` and `lena`; run `{run.status}`.")
    return "03-ambiguous.md", report(
        "Ambiguous: clarification before design", narrative, run, engine
    )


class FailingSecurityAgents(AgentRegistry):
    """Injects a security finding, as if input validation had regressed."""

    def _security(self, ctx):
        result = super()._security(ctx)
        result["checks"]["rejects_non_public_destinations"] = False
        result["findings"] = ["rejects_non_public_destinations"]
        result["status"] = "passed_with_findings"
        return result


async def gate_blocked():
    engine = new_engine("blocked", FailingSecurityAgents(project_root=ROOT))
    run = engine.create_run("greenfield", "Build a URL shortener", requested_by="priya")
    narrative = ["Same plan as greenfield, with a security regression injected into the review."]
    run = await engine.execute(run.id)
    engine.approve(run.id, "implement_orchestrator", True, "marcus", "Scope reviewed")
    run = await engine.execute(run.id)
    narrative.append(
        "The release-gate approval request carries the failing security evidence, so the "
        "approver can see it."
    )
    engine.approve(run.id, "release_gate", True, "lena", "Approving without reading evidence")
    run = await engine.execute(run.id)
    narrative.append(
        "Even with human approval, the evidence gate fails closed: the gate refusal is not "
        f"retried and the run ends `{run.status}`, not `succeeded`."
    )
    return "04-gate-blocked.md", report(
        "Validation: release gate fails closed on a security finding", narrative, run, engine
    )


async def main(out: Path):
    out.mkdir(parents=True, exist_ok=True)
    for scenario in (greenfield, brownfield, ambiguous, gate_blocked):
        name, text = await scenario()
        (out / name).write_text(text, encoding="utf-8")
        status = text.split("**Final status:** `")[1].split("`")[0]
        print(f"{name:22} {status}")
    print(f"Reports written to {out}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "scenario-runs")
    asyncio.run(main(parser.parse_args().out))
